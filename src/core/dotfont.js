export const GLYPHS = {};
for (const [ch, rows] of Object.entries(RAW)) { GLYPHS[ch] = rows; }
export const GLYPH_W = 5, GLYPH_H = 7;
/** Rasterise text onto a boolean grid. Returns { grid: Uint8Array(cols*rows), cols, rows } with 1 column spacing. */
export function rasterise(text, cols, rows = GLYPH_H, { offsetX = 0 } = {}) {
  const grid = new Uint8Array(cols * rows); let x = offsetX;
  for (const ch of text) {
    const g = GLYPHS[ch] || GLYPHS[ch.toUpperCase()] || GLYPHS['?'];
    for (let r = 0; r < GLYPH_H; r++) for (let c = 0; c < GLYPH_W; c++) if (g[r][c] === '#') { const xx = x + c; if (xx >= 0 && xx < cols && r < rows) grid[r * cols + xx] = 1; }
    x += GLYPH_W + 1;
  }
  return { grid, cols, rows, width: x - 1 };
}
export function textWidth(text) { return text.length * (GLYPH_W + 1) - 1; }
